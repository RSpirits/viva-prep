"""
Tests for the synthetic data generated by scripts/generate_synthetic_data.py.

Checks:
1. Exactly 18 submission files exist.
2. Every evidence sentence in the answer key occurs verbatim in its submission file.
3. Each misconception (M1–M6) appears at least twice across all submissions.
4. At least 3 submissions have no misconceptions.
"""

import json
import os
import pathlib
import pytest

# ---------------------------------------------------------------------------
# Locate data directory relative to this file
# ---------------------------------------------------------------------------

REPO_ROOT = pathlib.Path(__file__).parent.parent
SUBMISSIONS_DIR = REPO_ROOT / "data" / "submissions"
ANSWER_KEY_PATH = REPO_ROOT / "data" / "answer_key" / "answer_key.json"

ALL_MISCONCEPTIONS = ["M1", "M2", "M3", "M4", "M5", "M6"]


@pytest.fixture(scope="module")
def answer_key():
    assert ANSWER_KEY_PATH.exists(), (
        f"Answer key not found at {ANSWER_KEY_PATH}. "
        "Run scripts/generate_synthetic_data.py first."
    )
    with open(ANSWER_KEY_PATH, encoding="utf-8") as fh:
        return json.load(fh)


@pytest.fixture(scope="module")
def submission_texts():
    """Return a dict mapping student_id -> full file text."""
    texts = {}
    for path in sorted(SUBMISSIONS_DIR.glob("*.md")):
        student_id = path.stem
        texts[student_id] = path.read_text(encoding="utf-8")
    return texts


# ---------------------------------------------------------------------------
# Test 1: exactly 18 submission files
# ---------------------------------------------------------------------------

def test_18_submission_files(submission_texts):
    assert len(submission_texts) == 18, (
        f"Expected 18 submission files, found {len(submission_texts)}."
    )


# ---------------------------------------------------------------------------
# Test 2: every evidence sentence appears verbatim in its submission
# ---------------------------------------------------------------------------

def test_evidence_verbatim_in_submission(answer_key, submission_texts):
    failures = []
    for entry in answer_key:
        sid = entry["student_id"]
        misconceptions = entry.get("misconceptions", [])
        evidence_field = entry.get("evidence", "")

        if not misconceptions:
            # Nothing to verify for clean submissions
            continue

        if sid not in submission_texts:
            failures.append(f"{sid}: submission file not found")
            continue

        text = submission_texts[sid]

        # Evidence field may contain multiple sentences joined by " | "
        evidences = [e.strip() for e in evidence_field.split(" | ") if e.strip()]

        for evidence in evidences:
            # Skip the absence-based M5 marker
            if evidence == "(no assumptions or limitations mentioned)":
                continue
            if evidence not in text:
                failures.append(
                    f"{sid}: evidence not found verbatim in submission.\n"
                    f"  Evidence: {evidence!r}\n"
                    f"  Text (first 300 chars): {text[:300]!r}"
                )

    assert not failures, "Evidence verbatim check failed:\n" + "\n".join(failures)


# ---------------------------------------------------------------------------
# Test 3: each misconception appears at least twice
# ---------------------------------------------------------------------------

def test_each_misconception_at_least_twice(answer_key):
    counts = {m: 0 for m in ALL_MISCONCEPTIONS}
    for entry in answer_key:
        for m in entry.get("misconceptions", []):
            if m in counts:
                counts[m] += 1

    under = {m: c for m, c in counts.items() if c < 2}
    assert not under, (
        "The following misconceptions appear fewer than twice: "
        + ", ".join(f"{m} (count={c})" for m, c in under.items())
    )


# ---------------------------------------------------------------------------
# Test 4: at least 3 submissions have no misconceptions
# ---------------------------------------------------------------------------

def test_at_least_3_clean_submissions(answer_key):
    clean = [e for e in answer_key if not e.get("misconceptions")]
    assert len(clean) >= 3, (
        f"Expected at least 3 clean submissions, found {len(clean)}."
    )


# ---------------------------------------------------------------------------
# Test 5: every answer body is 250–400 words
# ---------------------------------------------------------------------------

def test_answer_body_word_count(submission_texts):
    out_of_range = {}
    for sid, text in sorted(submission_texts.items()):
        # Strip the YAML front-matter block (everything up to and including the
        # closing "---" line) before counting.
        body = text
        if text.startswith("---"):
            second_dash = text.index("---", 3)
            body = text[second_dash + 3:].lstrip("\n")
        word_count = len(body.split())
        if not (250 <= word_count <= 400):
            out_of_range[sid] = word_count

    assert not out_of_range, (
        "The following submissions have word counts outside 250–400:\n"
        + "\n".join(f"  {sid}: {wc} words" for sid, wc in sorted(out_of_range.items()))
    )


# ---------------------------------------------------------------------------
# Test 6: no evidence sentence appears in more than one submission
# ---------------------------------------------------------------------------

def test_evidence_sentences_are_unique(answer_key, submission_texts):
    """Each non-M5 evidence sentence must appear in exactly one submission file."""
    # Build a map: evidence_string -> list of student_ids where it was found
    evidence_to_students: dict = {}

    for entry in answer_key:
        sid = entry["student_id"]
        evidence_field = entry.get("evidence", "")
        if not evidence_field:
            continue
        evidences = [e.strip() for e in evidence_field.split(" | ") if e.strip()]
        for ev in evidences:
            if ev == "(no assumptions or limitations mentioned)":
                continue
            evidence_to_students.setdefault(ev, []).append(sid)

    duplicates = {ev: sids for ev, sids in evidence_to_students.items() if len(sids) > 1}

    assert not duplicates, (
        "The following evidence sentences appear in more than one submission:\n"
        + "\n".join(
            f"  {sids!r}: {ev!r}" for ev, sids in duplicates.items()
        )
    )
